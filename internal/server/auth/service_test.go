func TestService_Login_success(t *testing.T) {
	t.Parallel()
	ctx := context.Background()
	ctrl := gomock.NewController(t)
	svc, users, _, authTx, hasher, issuer := newTestService(ctrl, nil)
	u := &auth.User{
		UserID:                 "user-1",
		Login:                  "alice",
		PasswordHash:           []byte("hash"),
		PasswordSalt:           []byte("salt"),
		KDFAlgorithm:           "argon2id",
		KDFMemoryKiB:           1,
		KDFIterations:          2,
		KDFParallelism:         3,
		KDFKeyLength:           32,
		EncryptedVaultKey:      []byte("k"),
		EncryptedVaultKeyNonce: []byte("n"),
	}
	users.EXPECT().GetByLogin(gomock.Any(), "alice").Return(u, nil)
	hasher.EXPECT().Compare(u.PasswordHash, "pw").Return(nil)
	authTx.EXPECT().LoginWithDeviceAndSession(gomock.Any(), gomock.Any(), gomock.Any()).Return(nil)
	issuer.EXPECT().IssueAccessToken(gomock.Any(), gomock.Any()).Return("jwt-access", nil)

	out, err := svc.Login(ctx, auth.LoginInput{Login: "alice", Password: "pw", DeviceID: "dev-1"})
	if err != nil {
		t.Fatal(err)
	}
	if out.UserID != "user-1" || out.Login != "alice" || out.DeviceID != "dev-1" {
		t.Fatalf("unexpected %+v", out)
	}
	if out.AccessToken != "jwt-access" || out.RefreshToken == "" {
		t.Fatal("missing tokens")
	}
	if string(out.PasswordSalt) != "salt" || string(out.EncryptedVaultKey) != "k" {
		t.Fatal("vault metadata not propagated")
	}
}

