func TestService_Register_success(t *testing.T) {
	t.Parallel()
	ctx := context.Background()
	ctrl := gomock.NewController(t)
	svc, _, _, authTx, hasher, issuer := newTestService(ctrl, nil)
	hasher.EXPECT().Hash("pw").Return([]byte("h"), nil)
	authTx.EXPECT().RegisterWithSession(gomock.Any(), gomock.Any(), gomock.Any(), gomock.Any()).Return(nil)
	issuer.EXPECT().IssueAccessToken(gomock.Any(), gomock.Any()).DoAndReturn(
		func(c auth.AccessTokenClaims, ttl time.Duration) (string, error) {
			if c.UserID == "" || c.DeviceID == "" {
				t.Error("expected non-empty UserID and DeviceID in claims")
			}
			if ttl != time.Minute {
				t.Errorf("ttl %v, want 1m", ttl)
			}
			return "access-jwt", nil
		})

	out, err := svc.Register(ctx, auth.RegisterInput{Login: "u", Password: "pw"})
	if err != nil {
		t.Fatal(err)
	}
	if out.Login != "u" || out.UserID == "" || out.DeviceID == "" {
		t.Fatalf("unexpected output: %+v", out)
	}
	if out.AccessToken != "access-jwt" || out.RefreshToken == "" {
		t.Fatalf("tokens: access=%q refresh empty=%v", out.AccessToken, out.RefreshToken == "")
	}
}

