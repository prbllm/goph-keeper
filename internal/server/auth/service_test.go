func fixedClock() auth.Clock {
	t0 := time.Date(2025, 3, 1, 12, 0, 0, 0, time.UTC)
	return func() time.Time { return t0 }
}

func newTestService(ctrl *gomock.Controller, now auth.Clock) (
	*auth.Service,
	*mocks.MockUserRepository,
	*mocks.MockSessionRepository,
	*mocks.MockAuthTx,
	*mocks.MockPasswordHasher,
	*mocks.MockTokenIssuer,
) {
	if now == nil {
		now = fixedClock()
	}
	users := mocks.NewMockUserRepository(ctrl)
	sessions := mocks.NewMockSessionRepository(ctrl)
	authTx := mocks.NewMockAuthTx(ctrl)
	hasher := mocks.NewMockPasswordHasher(ctrl)
	issuer := mocks.NewMockTokenIssuer(ctrl)
	svc := auth.NewService(
		users, sessions, authTx, hasher, issuer, now,
		time.Minute, time.Hour,
		65536, 104857600, 8388608,
	)
	return svc, users, sessions, authTx, hasher, issuer
}

